-- ============================================================
--  Міграція 019: Примусова 2FA для привілейованих ролей.
--
--  Для ролей admin та manager двофакторна автентифікація обов'язкова.
--  Вмикаємо прапорець twofa_enabled для всіх існуючих таких акаунтів,
--  щоб профіль коректно відображав стан 2FA. Сам вхід для цих ролей
--  захищений незалежно від прапорця (див. isMandatory2faRole у коді).
--
--  Безпечно запускати повторно (UPDATE ідемпотентний).
-- ============================================================

UPDATE public.users
   SET twofa_enabled = true
 WHERE role IN ('admin', 'manager')
   AND twofa_enabled = false;
